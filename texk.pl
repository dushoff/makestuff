use strict;
use 5.10.0;

## Scan a top-level .tex file, following \input and \include recursively,
## and write a single flat set of make rules for the whole tree
## See texk.md

my $top = $ARGV[0];
my $basename = $top;
$basename =~ s/\.tex$//;

my $target = "$basename.tex.deps";
my $mkfile = "$basename.texk.mk";

my (@inputs, @graphics, @bibs, %seen);

scan($top);

sub add {
	my ($list, $f) = @_;
	return if $seen{$f}++;
	push @$list, $f;
}

## Paths are relative to the directory where latex runs, at any depth
sub scan {
	my ($file) = @_;
	open(my $fh, "<", $file) or return; ## Not made yet; listed but not scanned
	local $/;
	my $f = <$fh>;
	close $fh;

	return if $f =~ /%.*no_texdeps/;
	$f =~ s/(?<!\\)%.*//g;

	my @found;
	while ($f =~ /\\(input|include|includegraphics|bibliography|addbibresource)\s*(?:\[[^\]]*\])?\s*\{(.*?)\}/g){
		my ($cmd, $arg) = ($1, $2);
		if ($cmd eq "includegraphics"){
			add(\@graphics, $arg);
		} elsif ($cmd =~ /^(?:bibliography|addbibresource)$/){
			foreach (split /,\s*/, $arg){
				s/\.bib$//;
				add(\@bibs, "$_.bib");
			}
		} else {
			## Add .tex unless there is already an extension
			$arg .= ".tex" unless $arg =~ m|\.[^/]*$|;
			add(\@inputs, $arg);
			push @found, $arg if $arg =~ /\.tex$/;
		}
	}
	scan($_) foreach @found;
}

######################################################################
### Write rules

## First-level directories, order-only so that they get made (e.g., cloned)
## but changes inside them don't count as changes
my %dirs;
foreach (@inputs, @graphics, @bibs){
	$dirs{$1} = 1 if m|^([^/.][^/]*)/|;
}
my $dirdep = %dirs ? " | " . join " ", sort keys %dirs : "";

say "## Generated by makestuff/texk.pl from $top; do not edit";
say "";
say "## Rescan when any scanned file changes";
say "$mkfile: $top @inputs$dirdep";
say "";
say "## Everything the document depends on; pictures before the bibliography";
say "## so they exist before latex runs for bibtex";
say "$target: @inputs" if @inputs;
say "$target: @graphics" if @graphics;
if (@bibs){
	say "$target: $basename.bbl";
	say "$basename.bbl: @bibs";
}
say "$target:$dirdep" if %dirs;
