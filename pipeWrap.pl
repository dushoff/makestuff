use strict;
use 5.10.0;

## Convert `make -n <goal>` output into a shell script (stdout)
## plus one R wrapper file per pipeR target (pipeWrap/<target>.R)
## Usage: perl pipeWrap.pl <goal> <make log> > pipeWrap/<goal>.sh
## See %.pipeWrap in pipeR.mk

my $dir = "pipeWrap";
my $goal = shift @ARGV;

say "#!/bin/sh";
say "## Does what `make $goal` would do, without make";
say "## Run from the top directory: sh $dir/$goal.sh";
say "## Generated by makestuff/pipeWrap.pl; edit the source scripts, not this file";
say "set -e";

my $making;
while (<>){
	chomp;

	if (/^echo (pipeR: Making .*)/){
		$making = $1;
		next;
	}

	## pipeR call: R --vanilla --args <target> shellpipes <stem>.pipestar <deps> < <script> > <target>
	if (/R --vanilla --args (\S+) shellpipes (.*?) < (\S+) > \S+\)/){
		my ($target, $rest, $script) = ($1, $2, $3);
		my $call = "$target $rest";
		my $wrapper = "$dir/$target.R";
		say "";
		say "## $making" if defined $making;
		say "## rpcall(\"$call\")";
		print `perl -npe "last unless /^#/" $script` if -e $script;
		say "R --vanilla < $wrapper > $target";
		writeWrapper($wrapper, $target, $call, $script);
		undef $making;
		next;
	}

	if (/^mkdir (?:-p )?(\S+)$/){
		say "mkdir -p $1";
		next;
	}

	if (/^(?:\/bin\/)?cp (?:-f )?(\S+) (\S+)$/){
		say "cp $1 $2";
		next;
	}

	## make wanted a pdf from a pipeR target
	if (/^\/bin\/ls (\S+\.Rout)\.pdf > \/dev\/null \|\| \(ls \S+\.pdf\.tmp/){
		say "[ -f $1.pdf ] || { echo \"ERROR: $1 did not make $1.pdf (startGraphics() missing?)\" >&2; exit 1; }";
		next;
	}
}

sub writeWrapper {
	my ($wrapper, $target, $call, $script) = @_;
	(my $wdir = $wrapper) =~ s|/[^/]+$||;
	system("mkdir", "-p", $wdir) == 0 or die "Can't make $wdir";
	open(my $fh, ">", $wrapper) or die "Can't write $wrapper";
	print $fh <<"END";
## pipeWrap wrapper for $target; run from the top directory
## Generated by makestuff/pipeWrap.pl; edit $script, not this file
library(shellpipes)
rpcall("$call")
options(device=function(...) stop("Plotting without startGraphics()", call.=FALSE))
source("$script", echo=TRUE, max.deparse.length=Inf)
END
	close $fh;
}
