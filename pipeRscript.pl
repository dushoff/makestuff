use strict;
use 5.10.0;

## Convert `make -n` output into a stand-alone R script
## for people who want to run a pipeR pipeline without make
## Used by %.Rscript in pipeR.mk
## Translates pipeR calls and a few simple shell steps (mkdir, cp, pdf rescue);
## everything else make would do is ignored

say "## Generated by makestuff/pipeRscript.pl; edit the source scripts, not this file";
say "library(shellpipes)";

while (<>){
	chomp;

	## pipeR call: R --vanilla --args <target> shellpipes <stem>.pipestar <deps> < <script> > <target>
	if (/R --vanilla --args (\S+) shellpipes (.*?) < (\S+) > \S+\)/){
		my ($target, $rest, $script) = ($1, $2, $3);
		say "\n######################################################################";
		say "## Making $target";
		print `perl -npe "last unless /^#/" $script` if -e $script;
		say 'rm(list=ls(all.names=TRUE))';
		say "rpcall(\"$target $rest\")";
		say "source(\"$script\")";
		say "graphics.off()";
		next;
	}

	if (/^mkdir (?:-p )?(\S+)$/){
		say "dir.create(\"$1\", showWarnings=FALSE, recursive=TRUE)";
		next;
	}

	if (/^(?:\/bin\/)?cp (?:-f )?(\S+) (\S+)$/){
		say "file.copy(\"$1\", \"$2\", overwrite=TRUE)";
		next;
	}

	## pdf rescue from %.Rout.pdf rule
	if (/^\/bin\/ls (\S+\.pdf) > \/dev\/null \|\| \(ls (\S+\.pdf\.tmp)/){
		say "if (!file.exists(\"$1\") && file.exists(\"$2\")) file.rename(\"$2\", \"$1\")";
		next;
	}
}
